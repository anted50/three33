export const PROVINCE_NAMES: readonly string[] = MN_PROVINCES.map((p) => p.name)

/** The сум/дүүрэг of a province; empty for a name we do not recognise. */
export function unitsForProvince(province: string): readonly string[] {
  return MN_PROVINCES.find((p) => p.name === province)?.units ?? []
}

/**
 * "Улаанбаатар, Хан-Уул, 24-р хороо" — the administrative part of an address,
 * written the way a courier reads it: widest first. Orders placed before the
 * form asked for аймаг/хот simply start at сум/дүүрэг.
 */
export function formatArea(address: {
  province?: string
  district: string
  khoroo: string
}): string {
  return [address.province, address.district, address.khoroo]
    .filter(Boolean)
    .join(', ')
}
