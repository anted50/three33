/**
 * Mongolia's administrative divisions, as the address form needs them:
 * аймаг/хот → сум/дүүрэг → баг/хороо.
 *
 * The first two levels are closed sets, so they are selects and the values
 * stored in orders.shipping_address_snapshot are canonical — a courier list
 * grouped by сум is only groupable if everyone spelled it the same way.
 * The third level (баг/хороо) is left as free text: its numbering changes with
 * every redistricting, and a stale dropdown would block a real address.
 *
 * Lives in ~/lib rather than ~/lib/server because the checkout form renders it
 * in the browser.
 */

